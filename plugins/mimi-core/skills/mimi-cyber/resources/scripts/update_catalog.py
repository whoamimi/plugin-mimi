#!/usr/bin/env python3
"""Rebuild the category and tag index files from the YAML catalogs.

usage: python3 -I update_catalog.py [--check]

Reads actors.yml, checks.yml, strategy.yml and attacks.yml next to this
script, validates them, and writes the six index files in the skill root:
security_/ai_/attack_ x categories/tags .md. Each lists unique labels as
sorted bullet points. With --check, nothing is written and the exit code is
1 if any index is out of date or the YAML has problems. Deps: PyYAML.
"""
import argparse
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("PyYAML is required: pip install pyyaml")

HERE = Path(__file__).resolve().parent
SKILL = HERE.parent.parent
DOMAINS = {"SECURITY", "AI"}
SEVERITIES = {"NONE", "LOW", "MEDIUM", "HIGH", "EXTREME"}
UPPER = re.compile(r"^[A-Z0-9]+(_[A-Z0-9]+)*$")
LOWER = re.compile(r"^[a-z0-9]+(_[a-z0-9]+)*$")
HEADER = "<!-- Generated by resources/scripts/update_catalog.py from the YAML catalogs. Do not edit by hand. -->\n"
TITLES = {
    "security_categories.md": "Security categories",
    "security_tags.md": "Security tags",
    "ai_categories.md": "AI governance and security categories",
    "ai_tags.md": "AI governance and security tags",
    "attack_categories.md": "Attack categories",
    "attack_tags.md": "Attack tags",
}

problems = []


def load(name):
    path = HERE / name
    try:
        data = yaml.safe_load(path.read_text()) or []
    except (OSError, yaml.YAMLError) as exc:
        problems.append(f"{name}: cannot read ({exc})")
        return []
    if not isinstance(data, list):
        problems.append(f"{name}: top level must be a list")
        return []
    return data


def need(name, rec, key, pattern=None):
    value = rec.get(key)
    where = f"{name}: {rec.get('label') or rec.get('audit_label') or '?'}"
    if value in (None, "", []):
        problems.append(f"{where}: missing '{key}'")
        return None
    values = value if isinstance(value, list) else [value]
    if pattern:
        for v in values:
            if not isinstance(v, str) or not pattern.match(v):
                problems.append(f"{where}: '{key}' value {v!r} has the wrong format")
    return value


def unique(name, records, key):
    seen = set()
    for r in records:
        label = r.get(key)
        if label in seen:
            problems.append(f"{name}: duplicate {key} '{label}'")
        seen.add(label)
    return seen


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="report out-of-date indexes without writing")
    a = ap.parse_args()

    actors, checks = load("actors.yml"), load("checks.yml")
    strategies, attacks = load("strategy.yml"), load("attacks.yml")

    strategy_labels = unique("strategy.yml", strategies, "label")
    for s in strategies:
        need("strategy.yml", s, "label", UPPER)
        need("strategy.yml", s, "defense")

    actor_labels = unique("actors.yml", actors, "label")
    for r in actors:
        need("actors.yml", r, "label", LOWER)
        need("actors.yml", r, "category", UPPER)
        need("actors.yml", r, "tags", UPPER)
        if r.get("domain") not in DOMAINS:
            problems.append(f"actors.yml: {r.get('label')}: domain must be one of {sorted(DOMAINS)}")
        for s in r.get("strategies") or []:
            if s not in strategy_labels:
                problems.append(f"actors.yml: {r.get('label')}: strategy '{s}' is not in strategy.yml")

    attack_labels = unique("attacks.yml", attacks, "label")
    for missing in sorted(actor_labels - attack_labels):
        problems.append(f"attacks.yml: missing index entry for '{missing}'")
    for extra in sorted(attack_labels - actor_labels):
        problems.append(f"attacks.yml: '{extra}' has no case study in actors.yml")

    unique("checks.yml", checks, "audit_label")
    for c in checks:
        need("checks.yml", c, "audit_label", LOWER)
        need("checks.yml", c, "audit_category", UPPER)
        need("checks.yml", c, "audit_tag", UPPER)
        if c.get("domain") not in DOMAINS:
            problems.append(f"checks.yml: {c.get('audit_label')}: domain must be one of {sorted(DOMAINS)}")
        for o in c.get("observations") or []:
            if o.get("severity") not in SEVERITIES:
                problems.append(f"checks.yml: {c.get('audit_label')}: severity {o.get('severity')!r} "
                                f"must be one of {sorted(SEVERITIES)}")

    def collect(records, key, domain=None):
        out = set()
        for r in records:
            if domain and r.get("domain") != domain:
                continue
            value = r.get(key) or []
            out.update(value if isinstance(value, list) else [value])
        return out

    indexes = {
        "security_categories.md": collect(checks, "audit_category", "SECURITY"),
        "security_tags.md": collect(checks, "audit_tag", "SECURITY"),
        "ai_categories.md": collect(checks, "audit_category", "AI"),
        "ai_tags.md": collect(checks, "audit_tag", "AI"),
        "attack_categories.md": collect(actors, "category"),
        "attack_tags.md": collect(actors, "tags"),
    }

    stale = []
    for name, labels in indexes.items():
        body = HEADER + f"\n# {TITLES[name]}\n\n"
        body += "".join(f"- {label}\n" for label in sorted(labels)) if labels else "_None yet._\n"
        path = SKILL / name
        current = path.read_text() if path.exists() else None
        if current != body:
            stale.append(name)
            if not a.check:
                path.write_text(body)
        print(f"{name:<24} {len(labels)} label(s)")

    for p in problems:
        print(f"problem: {p}")
    if a.check:
        for name in stale:
            print(f"out of date: {name} (run update_catalog.py)")
        return 1 if stale or problems else 0
    print(f"updated {len(stale)} file(s)" if stale else "all indexes already up to date")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
